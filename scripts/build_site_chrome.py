def legal_body(slug: str, tr_body: str) -> str:
    """Turkish text, plus the English translation (site/legal/en/<slug>.md) shown when the page is in English."""
    en_path = os.path.join(ROOT, "site", "legal", "en", slug + ".md")
    if not os.path.exists(en_path):
        return md(fill(tr_body))
    en_body = open(en_path, encoding="utf-8").read().partition("\n---\n")[2]
    return ('<div data-lang="tr" lang="tr">\n' + md(fill(tr_body)) + '\n</div>\n<div data-lang="en" lang="en">\n'
            + md(fill(en_body)) + '\n</div>')


def legal_pages():
    src = os.path.join(ROOT, "site", "legal")
    docs = []
    for fn in sorted(os.listdir(src)):
        if fn.endswith(".md"):
            text = open(os.path.join(src, fn), encoding="utf-8").read()
            meta, _, body = text.partition("\n---\n")
            m = dict(re.findall(r"^(\w+):\s*(.+)$", meta, re.M))
            docs.append((int(m.get("order", 9)), fn[:-3], m, body))
    docs.sort()
    out = {}
    for _, slug, m, body in docs:
        side = "".join(
            '<li><a href="{}.html"{}{}>{}</a></li>'.format(
                s,
                ' aria-current="page"' if s == slug else "",
                ' data-i18n="{}"'.format(LEGAL_I18N_MAP[s]) if s in LEGAL_I18N_MAP else "",
                html.escape(mm["title"]),
            )
            for _, s, mm, _ in docs
        )
        page = LEGAL_HEAD.format(
            title=html.escape(m["title"]), desc=html.escape(m.get("description", m["title"])),
            version_label='<span data-lang="tr">SÜRÜM {0}</span><span data-lang="en">VERSION {0}</span>'.format(CFG["legal_version"]), nav=nav("legal", "../"), foot=footer("../"), side=side,
            status_tr=html.escape(CFG["legal_status_tr"]), status_en=html.escape(CFG["legal_status_en"]),
            body=legal_body(slug, body), asset_v=ASSET_V)
        out["legal/{}.html".format(slug)] = page
    return out


ASSET_V = "20261028_v7"   # cache-busting token for the shared pro assets; keep in step with the pages


MAIL_TEXTS = ("on-bilgilendirme", "mesafeli-satis")


def legal_texts():
    """Plain-text copies of the two pre-contract texts; the API attaches them to the order confirmation e-mail
    (durable medium, Mesafeli Sözleşmeler Yönetmeliği)."""
    src = os.path.join(ROOT, "site", "legal")
    out = {}
    for slug in MAIL_TEXTS:
        meta, _, body = open(os.path.join(src, slug + ".md"), encoding="utf-8").read().partition("\n---\n")
        title = dict(re.findall(r"^(\w+):\s*(.+)$", meta, re.M))["title"]
        body = fill(body)
        body = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", lambda m: m.group(1) + (" (" + m.group(2) + ")" if m.group(2).startswith("http") else
                      " (https://answerr.me/pro/legal/" + m.group(2).replace("../", "../") + ")"), body)
        body = body.replace("https://answerr.me/pro/legal/../", "https://answerr.me/pro/").replace("**", "")
        out["commerce/legal/{}.txt".format(slug)] = "{}\n{}\n\n{}\n".format(title, CFG["company"]["legal_name"], body.strip())
    return out


def root_index(pro_text: str) -> str:
    def fix_attr(m):
        attr, val = m.group(1), m.group(2)
        if val.startswith(("http://", "https://", "mailto:", "data:", "#")):
            return m.group(0)
        if val.startswith("../"):
            return '{}="{}"'.format(attr, val[3:])
        if val == "index.html" or val.startswith("index.html#"):
            return m.group(0)
        return '{}="pro/{}"'.format(attr, val)
    return re.sub(r'\b(href|src|srcset)="([^"]+)"', fix_attr, pro_text)


def build(check: bool) -> int:
    stale = []
    for rel, (active, r) in PAGES.items():
        path = os.path.join(PRO, rel)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        new = splice(text, NAV_START, NAV_END, nav(active, r), r'<nav class="nav".*?</nav>')
        new = splice(new, FOOT_START, FOOT_END, footer(r), r"<footer>.*?</footer>")
        if new != text:
            stale.append(rel)
            if not check:
                open(path, "w", encoding="utf-8").write(new)
    pro_idx = open(os.path.join(PRO, "index.html"), encoding="utf-8").read()
    root_idx_path = os.path.join(ROOT, "index.html")
    want_root = root_index(pro_idx)
    old_root = open(root_idx_path, encoding="utf-8").read() if os.path.exists(root_idx_path) else None
    if old_root != want_root:
        stale.append("../index.html")
        if not check:
            open(root_idx_path, "w", encoding="utf-8").write(want_root)
    for rel, page in legal_pages().items():
        path = os.path.join(PRO, rel)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != page:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(page)
    for rel, text in legal_texts().items():
        path = os.path.join(ROOT, rel)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(text)
    if check and stale:
        print("out of date:", ", ".join(stale))
        return 1
    print(("up to date" if check else "written: " + (", ".join(stale) or "nothing")))
    return 0


if __name__ == "__main__":
    sys.exit(build("--check" in sys.argv))
