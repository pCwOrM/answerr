def splice(text: str, start: str, end: str, block: str, legacy: str) -> str:
    if start in text and end in text:
        a = text.index(start)
        a = text.rfind("\n", 0, a) + 1
        b = text.index(end) + len(end)
        return text[:a] + "  " + block.lstrip() + text[b:]
    m = re.search(legacy, text, re.S)
    if not m:
        raise SystemExit("no chrome anchor found")
    a = text.rfind("\n", 0, m.start()) + 1
    return text[:a] + "  " + block.lstrip() + text[m.end():]


# ----------------------------------------------------------------------------- legal pages (tiny markdown)
def inline(s: str) -> str:
    s = html.escape(s, quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: '<a href="{}">{}</a>'.format(html.escape(m.group(2), quote=True), m.group(1)), s)
    return s


def fill(s: str) -> str:
    def rep(m):
        path = m.group(1).split(".")
        v = CFG
        for p in path:
            v = v.get(p, "") if isinstance(v, dict) else ""
        return str(v) if v else "—"
    return re.sub(r"\{\{([a-z_.]+)\}\}", rep, s)


def md(text: str) -> str:
    out, para, lst, table = [], [], None, []

    def flush():
        nonlocal para, lst, table
        if para:
            out.append("<p>{}</p>".format(inline(" ".join(para))))
            para = []
        if lst:
            tag, items = lst
            out.append("<{0}>{1}</{0}>".format(tag, "".join("<li>{}</li>".format(inline(i)) for i in items)))
            lst = None
        if table:
            rows = [[c.strip() for c in r.strip().strip("|").split("|")] for r in table if not re.match(r"^\|\s*:?-", r)]
            head = "".join("<th scope=\"col\">{}</th>".format(inline(c)) for c in rows[0])
            body = "".join("<tr>{}</tr>".format("".join("<td>{}</td>".format(inline(c)) for c in r)) for r in rows[1:])
            out.append('<div class="scroll-x"><table class="tests legal-table"><thead><tr>{}</tr></thead><tbody>{}</tbody></table></div>'.format(head, body))
            table = []

    for line in text.splitlines():
        s = line.rstrip()
        if not s.strip():
            flush(); continue
        if s.startswith("|"):
            if para or lst:
                flush()
            table.append(s); continue
        elif table:
            flush()
        m = re.match(r"^(#{1,3}) (.+)$", s)
        if m:
            flush()
            lvl = len(m.group(1)) + 0
            slug = re.sub(r"[^a-z0-9]+", "-", m.group(2).lower().translate(str.maketrans("çğıöşü", "cgiosu"))).strip("-")
            out.append('<h{0} id="{2}">{1}</h{0}>'.format(lvl, inline(m.group(2)), slug))
            continue
        m = re.match(r"^\s*(?:(-)|(\d+)\.) (.+)$", s)
        if m:
            tag = "ul" if m.group(1) else "ol"
            if para:
                flush()
            if lst and lst[0] != tag:
                flush()
            lst = lst or (tag, [])
            lst[1].append(m.group(3)); continue
        if s.startswith("> "):
            flush(); out.append('<p class="note">{}</p>'.format(inline(s[2:]))); continue
        if lst:
            flush()
        para.append(s.strip())
    flush()
    return "\n".join(out)


